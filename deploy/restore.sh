#!/usr/bin/env bash
# Trial restore of a backup into a SCRATCH database next to the real one (never into the real one).
#
#   deploy/restore.sh                 restore the newest dump in BACKUP_DIR, print table sizes, drop the scratch database
#   deploy/restore.sh FILE            restore that dump
#   deploy/restore.sh --keep [FILE]   keep the scratch database afterwards for inspection (drop it by hand later)
#
# The scratch database is named <POSTGRES_DB>_restore_test and lives in the same PostgreSQL container, so the real data
# is untouched. A dump that fails here is a backup you do not have. Do this after setting backups up and then monthly.
# To restore on another machine instead, see README.md.
set -euo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
compose_file=${FITIT_COMPOSE_FILE:-$script_dir/compose.yml}
env_file=${FITIT_ENV_FILE:-/etc/fitit/fitit.env}

log() {
  printf '%s restore: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"
}

keep=no
file=""
while [ $# -gt 0 ]; do
  case "$1" in
    --keep) keep=yes ;;
    -h | --help)
      sed -n '2,10p' "$0"
      exit 0
      ;;
    -*)
      log "unknown option $1"
      exit 2
      ;;
    *) file=$1 ;;
  esac
  shift
done

if [ ! -r "$env_file" ]; then
  log "cannot read env file $env_file"
  exit 1
fi

setting() {
  local name=$1 default=${2-} line value
  if [ -n "${!name:-}" ]; then
    printf '%s' "${!name}"
    return
  fi
  line=$(grep -E "^${name}=" "$env_file" | tail -n 1 || true)
  value=${line#*=}
  if [ -z "$line" ] || [ -z "$value" ]; then
    value=$default
  fi
  printf '%s' "$value"
}

dc() {
  docker compose --env-file "$env_file" -f "$compose_file" "$@"
}

# psql inside the db container, as the database user, over the local socket.
db_psql() {
  dc exec -T db sh -c 'exec psql --username "$POSTGRES_USER" -v ON_ERROR_STOP=1 -At "$@"' sh "$@"
}

if [ -z "$file" ]; then
  backup_dir=$(setting BACKUP_DIR /var/backups/fitit)
  # shellcheck disable=SC2012  # names are generated by backup.sh, plain ASCII
  file=$(ls -1t "$backup_dir"/fitit-*.dump 2>/dev/null | head -n 1 || true)
  if [ -z "$file" ]; then
    log "no dump found in $backup_dir"
    exit 1
  fi
fi
if [ ! -r "$file" ]; then
  log "cannot read $file"
  exit 1
fi

prod_db=$(setting POSTGRES_DB fitit)
scratch="${prod_db}_restore_test"
case "$scratch" in
  *[!a-z0-9_]* | '')
    log "POSTGRES_DB '$prod_db' gives an unusable scratch name '$scratch'"
    exit 1
    ;;
esac
if [ "$scratch" = "$prod_db" ]; then
  log "refusing to restore into the real database"
  exit 1
fi

drop_scratch() {
  db_psql -d postgres -c "DROP DATABASE IF EXISTS $scratch WITH (FORCE)" >/dev/null
}

finish() {
  local code=$?
  if [ "$keep" = no ]; then
    drop_scratch || log "could not drop $scratch, drop it by hand"
  else
    log "kept $scratch (drop it with: docker compose exec db psql -U $(setting POSTGRES_USER fitit) -d postgres -c 'DROP DATABASE $scratch')"
  fi
  if [ "$code" -ne 0 ]; then
    log "FAILED with exit code $code"
  fi
  exit "$code"
}

log "dump: $file ($(du -h "$file" | cut -f1), written $(date -u -r "$file" +%Y-%m-%dT%H:%M:%SZ))"
drop_scratch
db_psql -d postgres -c "CREATE DATABASE $scratch" >/dev/null
trap finish EXIT

log "restoring into $scratch"
dc exec -T db sh -c 'exec pg_restore --username "$POSTGRES_USER" --no-owner --exit-on-error --dbname "$1"' sh "$scratch" <"$file"

log "tables in $scratch (name, rows):"
report=$(db_psql -d "$scratch" -F ' ' -c "
  SELECT table_schema || '.' || table_name,
         (xpath('/row/c/text()', query_to_xml(format('SELECT count(*) AS c FROM %I.%I', table_schema, table_name), false, true, '')))[1]::text
  FROM information_schema.tables
  WHERE table_type = 'BASE TABLE' AND table_schema NOT IN ('pg_catalog', 'information_schema')
  ORDER BY 1")
if [ -z "$report" ]; then
  log "the restored database has no tables"
  exit 1
fi
printf '%s\n' "$report"
log "OK: the dump restores cleanly"
